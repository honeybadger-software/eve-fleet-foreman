"""
build_refine_data.py  --  pull authoritative ore->mineral reprocessing yields.

Reprocessing yields aren't in ESI, they live in CCP's Static Data Export (SDE).
We grab the `invTypeMaterials` table (hosted as CSV by Fuzzwork) and the per-ore
`portion_size` (the reprocess batch size) from ESI, then write `refine_data.py`.

  REPROCESS = { ore_type_id: {"portion": N, "materials": {mineral_id: qty, ...}} }

`qty` = minerals produced from reprocessing one `portion` (batch) of the ore at
100% efficiency. The app applies skill/structure efficiency on top of this.

Run:  python build_refine_data.py
"""
import csv
import io
import json
import os
import requests

import ore_data

SDE_URL = "https://www.fuzzwork.co.uk/dump/latest/invTypeMaterials.csv"
ESI = "https://esi.evetech.net/latest"
HEADERS = {"User-Agent": "eve_foreman/0.1 (honeybadger.software) personal fleet tool"}
OUT_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "refine_data.py")


def main():
    ore_ids = set(ore_data.ORE_TYPE_IDS)
    mineral_ids = set(m["type_id"] for m in ore_data.MINERALS)

    # 1) reprocessing materials from the SDE CSV (typeID, materialTypeID, quantity)
    print(f"Downloading SDE invTypeMaterials ...")
    r = requests.get(SDE_URL, headers=HEADERS, timeout=120)
    r.raise_for_status()
    reader = csv.DictReader(io.StringIO(r.text))
    print("  columns:", reader.fieldnames)

    materials = {tid: {} for tid in ore_ids}
    for row in reader:
        try:
            tid = int(row["typeID"])
        except (KeyError, ValueError, TypeError):
            continue
        if tid in ore_ids:
            mtid = int(row["materialTypeID"])
            qty = int(row["quantity"])
            if mtid in mineral_ids:  # keep only the 8 refinable minerals
                materials[tid][mtid] = qty

    # 2) portion_size per ore from ESI
    print("Fetching portion sizes from ESI ...")
    reprocess = {}
    for o in ore_data.ORES:
        tid = o["type_id"]
        j = requests.get(f"{ESI}/universe/types/{tid}/", headers=HEADERS, timeout=30).json()
        portion = j.get("portion_size", 1)
        reprocess[tid] = {"portion": portion, "materials": materials.get(tid, {})}
        nice = ", ".join(f"{ore_data.MINERALS and next((m['name'] for m in ore_data.MINERALS if m['type_id']==k), k)}:{v}"
                         for k, v in materials.get(tid, {}).items())
        print(f"  {o['name']:<14} portion={portion:<4} -> {nice}")

    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write('"""AUTO-GENERATED by build_refine_data.py (CCP SDE + ESI). Do not edit by hand."""\n\n')
        f.write("# ore_type_id -> {portion: batch size, materials: {mineral_type_id: qty per batch}}\n")
        f.write("REPROCESS = " + json.dumps({str(k): v for k, v in reprocess.items()}, indent=4) + "\n")

    print(f"\nWrote refine_data.py for {len(reprocess)} ores.")


if __name__ == "__main__":
    main()
