"""
build_ore_data.py  --  one-time data builder for EVE Fleet Foreman.

Resolves ore + mineral type IDs and per-unit volumes straight from CCP's
official ESI API, then writes a verified `ore_data.py` the app imports.

Why a builder instead of hard-coded numbers?  So the IDs/volumes are CCP's
own values, not something we guessed from memory. Re-run any time CCP adds ore.

Run:  python build_ore_data.py
"""
import json
import os
import requests

# Always write next to this script, regardless of where it's run from.
OUT_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ore_data.py")

ESI = "https://esi.evetech.net/latest"
# CCP asks third-party apps to identify themselves in the User-Agent.
HEADERS = {"User-Agent": "eve_foreman/0.1 (honeybadger.software) personal fleet tool"}

# Base asteroid ores across all security space. Variants (Concentrated/Dense/etc.)
# and ice/moon ores can be appended to this list later -- the builder handles any
# valid name automatically.
ORE_NAMES = [
    # Highsec
    "Veldspar", "Scordite", "Pyroxeres", "Plagioclase",
    "Omber", "Kernite", "Jaspet", "Hemorphite", "Hedbergite",
    # Low / Null / wormhole
    "Gneiss", "Dark Ochre", "Crokite", "Spodumain",
    "Bistot", "Arkonor", "Mercoxit",
]

# The 8 minerals ore refines into (used by the appraiser / refine calc later).
MINERAL_NAMES = [
    "Tritanium", "Pyerite", "Mexallon", "Isogen",
    "Nocxium", "Zydrine", "Megacyte", "Morphite",
]


def resolve_ids(names):
    """POST a list of names -> {name: type_id} using ESI's bulk resolver."""
    r = requests.post(f"{ESI}/universe/ids/", json=names, headers=HEADERS, timeout=30)
    r.raise_for_status()
    found = {t["name"]: t["id"] for t in r.json().get("inventory_types", [])}
    missing = [n for n in names if n not in found]
    if missing:
        print(f"  !! could not resolve: {missing}")
    return found


def type_volume(type_id):
    """GET a single type -> (name, volume_m3, group_id)."""
    r = requests.get(f"{ESI}/universe/types/{type_id}/", headers=HEADERS, timeout=30)
    r.raise_for_status()
    j = r.json()
    return j["name"], j.get("volume"), j.get("group_id")


def main():
    print("Resolving ore IDs from ESI...")
    ore_ids = resolve_ids(ORE_NAMES)
    print("Resolving mineral IDs from ESI...")
    min_ids = resolve_ids(MINERAL_NAMES)

    ores = []
    for name in ORE_NAMES:
        tid = ore_ids.get(name)
        if not tid:
            continue
        real_name, vol, grp = type_volume(tid)
        ores.append({"name": real_name, "type_id": tid, "volume": vol, "group_id": grp})
        print(f"  {real_name:<14} id={tid:<6} vol={vol} m3")

    minerals = []
    for name in MINERAL_NAMES:
        tid = min_ids.get(name)
        if tid:
            minerals.append({"name": name, "type_id": tid})

    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write('"""AUTO-GENERATED by build_ore_data.py from CCP ESI. Do not edit by hand."""\n\n')
        f.write("# Each ore: name, ESI type_id, per-unit volume in m3, ESI group_id\n")
        f.write("ORES = " + json.dumps(ores, indent=4) + "\n\n")
        f.write("MINERALS = " + json.dumps(minerals, indent=4) + "\n\n")
        f.write("ORE_TYPE_IDS = [o['type_id'] for o in ORES]\n")
        f.write("MINERAL_TYPE_IDS = [m['type_id'] for m in MINERALS]\n")

    print(f"\nWrote ore_data.py: {len(ores)} ores, {len(minerals)} minerals.")


if __name__ == "__main__":
    main()
